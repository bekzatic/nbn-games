/* ==========================================================
   NBN GAMES — calm 8-bit (chiptune) background music (🎵 button)
   Author: Nursultan Rassulov
   Assignment #5 — Sound + Objects & methods + Arrays & loops.

   The music is GENERATED by the Web Audio API, like on old game
   consoles — no audio files, no copyright problems, nothing to download.
   It is our own tune, written as ARRAYS of notes:
     - key A minor, 96 BPM, chords Am → F → C → G
     - lead: square wave melody, two phrases (A, B) that take turns
     - arpeggio: quiet square-wave chord notes on every 8th note
     - bass: triangle wave, like the NES bass channel
     - hi-hat: a tiny burst of noise on the off-beats
   The loop is 8 bars (~20 s), then it starts again.

   Rules:
     - OFF by default; browsers only allow sound after a click,
       so it starts when the user presses 🎵.
     - The choice is remembered; on the next page it continues after
       the first click / key press.
     - The 🔊 / M mute (js/sound.js) also silences the music.
     - Pauses when the tab is hidden (saves battery).
   ========================================================== */

const Music = {
  KEY: 'nbn-music',
  VOLUME: 0.5,               // master level; every voice below is quiet on its own
  BPM: 96,
  STEPS_PER_BAR: 16,         // 16th notes

  // chords: arpeggio notes (MIDI numbers) + bass root
  CHORDS: [
    { name: 'Am', arp: [57, 60, 64, 69], bass: 45 },
    { name: 'F',  arp: [53, 57, 60, 65], bass: 41 },
    { name: 'C',  arp: [55, 60, 64, 67], bass: 48 },
    { name: 'G',  arp: [55, 59, 62, 67], bass: 43 }
  ],

  // melody: one array per bar, each note = [step 0–15, MIDI note, length in steps]
  PHRASES: {
    A: [
      [[0, 76, 2], [2, 81, 2], [4, 84, 3], [7, 83, 1], [8, 81, 4], [12, 76, 2], [14, 79, 2]],
      [[0, 77, 2], [2, 81, 2], [4, 84, 4], [8, 79, 2], [10, 81, 2], [12, 77, 4]],
      [[0, 76, 2], [2, 79, 2], [4, 84, 2], [6, 83, 2], [8, 79, 4], [12, 76, 2], [14, 74, 2]],
      [[0, 74, 2], [2, 79, 2], [4, 83, 3], [7, 81, 1], [8, 79, 6], [14, 71, 2]]
    ],
    B: [
      [[0, 72, 4], [4, 76, 2], [6, 79, 2], [8, 81, 6], [14, 83, 2]],
      [[0, 84, 4], [4, 81, 2], [6, 77, 2], [8, 81, 4], [12, 84, 4]],
      [[0, 79, 2], [2, 84, 2], [4, 88, 4], [8, 86, 2], [10, 84, 2], [12, 79, 4]],
      [[0, 83, 2], [2, 81, 2], [4, 79, 4], [8, 74, 2], [10, 79, 2], [12, 81, 4]]
    ]
  },
  ORDER: ['A', 'B'],          // phrase A, then phrase B, then again

  ctx: null,
  master: null,
  timer: null,
  step: 0,                    // 0 … 127 (8 bars × 16 steps)
  nextStepTime: 0,
  playing: false,

  stepSeconds() { return 60 / this.BPM / 4; },
  freq(midi) { return 440 * Math.pow(2, (midi - 69) / 12); },

  wanted() {
    try { return localStorage.getItem(this.KEY) === 'on'; } catch (e) { return false; }
  },

  remember(on) {
    try { localStorage.setItem(this.KEY, on ? 'on' : 'off'); } catch (e) { /* ignore */ }
  },

  // build the audio graph once: voices → low-pass → (dry + short echo) → master → speakers
  setup() {
    const AudioCtx = window.AudioContext || window.webkitAudioContext;
    if (!AudioCtx) return false;
    this.ctx = new AudioCtx();
    this.master = this.ctx.createGain();
    this.master.gain.value = 0;

    this.filter = this.ctx.createBiquadFilter();
    this.filter.type = 'lowpass';
    this.filter.frequency.value = 3200;          // takes the harsh edge off the square waves

    const delay = this.ctx.createDelay();
    delay.delayTime.value = this.stepSeconds() * 3;   // echo in time with the music
    const feedback = this.ctx.createGain();
    feedback.gain.value = 0.25;
    delay.connect(feedback).connect(delay);

    this.filter.connect(this.master);
    this.filter.connect(delay);
    delay.connect(this.master);
    this.master.connect(this.ctx.destination);

    // white noise for the hi-hat (made once)
    const len = Math.floor(this.ctx.sampleRate * 0.05);
    this.noise = this.ctx.createBuffer(1, len, this.ctx.sampleRate);
    const data = this.noise.getChannelData(0);
    for (let i = 0; i < len; i++) data[i] = Math.random() * 2 - 1;
    return true;
  },

  // one chiptune note: fast attack, short hold, soft release
  tone(midi, start, seconds, wave, volume) {
    const osc = this.ctx.createOscillator();
    const gain = this.ctx.createGain();
    osc.type = wave;
    osc.frequency.value = this.freq(midi);
    gain.gain.setValueAtTime(0.0001, start);
    gain.gain.linearRampToValueAtTime(volume, start + 0.01);
    gain.gain.setValueAtTime(volume, start + seconds * 0.7);
    gain.gain.linearRampToValueAtTime(0.0001, start + seconds);
    osc.connect(gain).connect(this.filter);
    osc.start(start);
    osc.stop(start + seconds + 0.02);
  },

  hat(start) {
    const src = this.ctx.createBufferSource();
    src.buffer = this.noise;
    const hp = this.ctx.createBiquadFilter();
    hp.type = 'highpass';
    hp.frequency.value = 7000;
    const gain = this.ctx.createGain();
    gain.gain.setValueAtTime(0.03, start);
    gain.gain.exponentialRampToValueAtTime(0.0001, start + 0.04);
    src.connect(hp).connect(gain).connect(this.filter);
    src.start(start);
  },

  // everything that sounds on one 16th-note step
  scheduleStep(step, t) {
    const len = this.stepSeconds();
    const bar = Math.floor(step / this.STEPS_PER_BAR);          // 0 … 7
    const inBar = step % this.STEPS_PER_BAR;                    // 0 … 15
    const chord = this.CHORDS[bar % this.CHORDS.length];
    const phrase = this.PHRASES[this.ORDER[Math.floor(bar / 4) % this.ORDER.length]];

    // bass: root on beats 1 and 3, the octave on beats 2 and 4
    if (inBar % 4 === 0) {
      const midi = inBar % 8 === 0 ? chord.bass : chord.bass + 12;
      this.tone(midi, t, len * 3.5, 'triangle', 0.16);
    }
    // arpeggio: chord notes going up on every 8th note
    if (inBar % 2 === 0) {
      this.tone(chord.arp[(inBar / 2) % chord.arp.length] + 12, t, len * 1.6, 'square', 0.022);
    }
    // hi-hat on the off-beats
    if (inBar % 4 === 2) this.hat(t);
    // melody notes that start on this step
    phrase[bar % 4].forEach(([at, midi, steps]) => {
      if (at === inBar) this.tone(midi, t, len * steps * 0.95, 'square', 0.05);
    });
  },

  // looks a little ahead and schedules the steps exactly in time
  tick() {
    const total = this.STEPS_PER_BAR * this.CHORDS.length * this.ORDER.length;   // 128 steps
    while (this.nextStepTime < this.ctx.currentTime + 0.3) {
      this.scheduleStep(this.step, this.nextStepTime);
      this.nextStepTime += this.stepSeconds();
      this.step = (this.step + 1) % total;
    }
  },

  start() {
    if (this.playing) return;
    if (!this.ctx && !this.setup()) return;
    if (this.ctx.state === 'suspended') this.ctx.resume();
    this.playing = true;
    this.step = 0;
    this.nextStepTime = this.ctx.currentTime + 0.1;
    this.tick();
    this.timer = setInterval(() => this.tick(), 100);
    this.applyVolume();
    this.paint();
  },

  stop() {
    if (!this.playing) return;
    this.playing = false;
    clearInterval(this.timer);
    const now = this.ctx.currentTime;
    this.master.gain.cancelScheduledValues(now);
    this.master.gain.setTargetAtTime(0, now, 0.4);   // smooth fade out
    setTimeout(() => { if (!this.playing && this.ctx) this.ctx.suspend(); }, 2500);
    this.paint();
  },

  toggle() {
    const on = !this.playing;
    this.remember(on);
    if (on) this.start(); else this.stop();
    if (window.showToast) showToast(on ? '🎵 8-bit music on' : 'Music off');
  },

  // follows the site-wide mute (🔊 button / M key)
  applyVolume() {
    if (!this.ctx) return;
    const muted = window.SoundFX && SoundFX.isMuted();
    const target = this.playing && !muted ? this.VOLUME : 0;
    this.master.gain.setTargetAtTime(target, this.ctx.currentTime, 0.8);   // slow fade in
  },

  paint() {
    document.querySelectorAll('[data-music-toggle]').forEach(btn => {
      btn.classList.toggle('active', this.playing);
      btn.setAttribute('aria-pressed', String(this.playing));
      btn.setAttribute('aria-label', this.playing ? 'Background music is on — turn off' : 'Turn on calm 8-bit background music');
      btn.title = this.playing ? 'Music on' : '8-bit music';
    });
  }
};

window.Music = Music;

document.addEventListener('DOMContentLoaded', () => {
  // the 🎵 button is created here, next to the 🔊 button (no extra HTML needed)
  document.querySelectorAll('[data-sound-toggle]').forEach(soundBtn => {
    const btn = document.createElement('button');
    btn.type = 'button';
    btn.className = 'btn btn-outline-secondary icon-btn music-btn';
    btn.setAttribute('data-music-toggle', '');
    btn.textContent = '🎵';
    btn.addEventListener('click', () => Music.toggle());
    soundBtn.after(btn);
  });
  Music.paint();

  // music was on before → continue after the first click or key press (browser rule)
  if (Music.wanted()) {
    const resume = e => {
      if (e.target.closest && e.target.closest('[data-music-toggle]')) return;   // the button handles itself
      Music.start();
    };
    document.addEventListener('pointerdown', resume, { once: true });
    document.addEventListener('keydown', resume, { once: true });
  }

  // 🔊 button or M key changed the mute state → follow it
  document.addEventListener('click', e => {
    if (e.target.closest('[data-sound-toggle]')) setTimeout(() => Music.applyVolume(), 0);
  });
  document.addEventListener('keydown', e => {
    if (e.key === 'm' || e.key === 'M') setTimeout(() => Music.applyVolume(), 0);
  });

  // pause in a hidden tab, continue when the user comes back
  document.addEventListener('visibilitychange', () => {
    if (!Music.ctx || !Music.playing) return;
    if (document.hidden) Music.ctx.suspend(); else Music.ctx.resume();
  });
});
