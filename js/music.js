/* ==========================================================
   NBN GAMES — relaxing background music (🎵 button in the navbar)
   Author: Nursultan Rassulov
   Assignment #5 — Sound + Objects & methods + Arrays & loops.

   The music is GENERATED by the Web Audio API — no audio files,
   no copyright problems, nothing to download.
     - soft "pad" chords: Cmaj7 → Am7 → Fmaj7 → G6, one chord every 6 s
     - quiet random notes of the C major pentatonic scale on top
     - a low-pass filter + echo (delay) make it warm and calm

   Rules:
     - OFF by default; browsers only allow sound after a click,
       so it starts when the user presses 🎵.
     - The choice is remembered; on the next page it continues after
       the first click / key press.
     - The 🔊 / M mute (js/sound.js) also silences the music.
     - Pauses when the tab is hidden (saves battery).
   ========================================================== */

const Music = {
  KEY: 'nbn-music',
  VOLUME: 0.06,              // quiet: it is background music
  CHORD_SECONDS: 6,

  // chords as arrays of frequencies (Hz)
  CHORDS: [
    [130.81, 164.81, 196.00, 246.94],   // Cmaj7: C3 E3 G3 B3
    [110.00, 130.81, 164.81, 196.00],   // Am7:   A2 C3 E3 G3
    [87.31, 130.81, 164.81, 220.00],    // Fmaj7: F2 C3 E3 A3
    [98.00, 146.83, 196.00, 246.94]     // G6:    G2 D3 G3 B3
  ],
  // C major pentatonic, two octaves higher, for the melody notes
  MELODY: [523.25, 587.33, 659.25, 783.99, 880.00, 1046.50],

  ctx: null,
  master: null,
  timer: null,
  chordIndex: 0,
  nextChordTime: 0,
  playing: false,

  wanted() {
    try { return localStorage.getItem(this.KEY) === 'on'; } catch (e) { return false; }
  },

  remember(on) {
    try { localStorage.setItem(this.KEY, on ? 'on' : 'off'); } catch (e) { /* ignore */ }
  },

  // build the audio graph once: notes → filter → (dry + echo) → master volume → speakers
  setup() {
    const AudioCtx = window.AudioContext || window.webkitAudioContext;
    if (!AudioCtx) return false;
    this.ctx = new AudioCtx();
    this.master = this.ctx.createGain();
    this.master.gain.value = 0;

    this.filter = this.ctx.createBiquadFilter();
    this.filter.type = 'lowpass';
    this.filter.frequency.value = 1400;

    const delay = this.ctx.createDelay();
    delay.delayTime.value = 0.45;
    const feedback = this.ctx.createGain();
    feedback.gain.value = 0.35;
    delay.connect(feedback).connect(delay);          // echo that slowly fades

    this.filter.connect(this.master);
    this.filter.connect(delay);
    delay.connect(this.master);
    this.master.connect(this.ctx.destination);
    return true;
  },

  // one soft note with a slow attack and release
  note(freq, start, length, type, volume) {
    const osc = this.ctx.createOscillator();
    const gain = this.ctx.createGain();
    osc.type = type;
    osc.frequency.value = freq;
    gain.gain.setValueAtTime(0.0001, start);
    gain.gain.linearRampToValueAtTime(volume, start + Math.min(1.5, length / 3));
    gain.gain.linearRampToValueAtTime(0.0001, start + length);
    osc.connect(gain).connect(this.filter);
    osc.start(start);
    osc.stop(start + length + 0.05);
  },

  // plays one chord + a few melody notes starting at time t
  scheduleBar(t) {
    const chord = this.CHORDS[this.chordIndex];
    for (const freq of chord) {
      this.note(freq, t, this.CHORD_SECONDS + 1.5, 'sine', 0.22);          // pad (overlaps the next chord)
      this.note(freq * 1.003, t, this.CHORD_SECONDS + 1.5, 'triangle', 0.06); // slightly detuned = warmer
    }
    // melody: up to 6 quiet notes, each on a random beat of the bar
    for (let beat = 0; beat < 6; beat++) {
      if (Math.random() < 0.45) {
        const freq = this.MELODY[Math.floor(Math.random() * this.MELODY.length)];
        this.note(freq, t + beat + Math.random() * 0.2, 2.2, 'sine', 0.07);
      }
    }
    this.chordIndex = (this.chordIndex + 1) % this.CHORDS.length;
  },

  // looks a little ahead and schedules the bars in time
  tick() {
    while (this.nextChordTime < this.ctx.currentTime + 1) {
      this.scheduleBar(this.nextChordTime);
      this.nextChordTime += this.CHORD_SECONDS;
    }
  },

  start() {
    if (this.playing) return;
    if (!this.ctx && !this.setup()) return;
    if (this.ctx.state === 'suspended') this.ctx.resume();
    this.playing = true;
    this.nextChordTime = this.ctx.currentTime + 0.1;
    this.tick();
    this.timer = setInterval(() => this.tick(), 500);
    this.applyVolume();
    this.paint();
  },

  stop() {
    if (!this.playing) return;
    this.playing = false;
    clearInterval(this.timer);
    const now = this.ctx.currentTime;
    this.master.gain.cancelScheduledValues(now);
    this.master.gain.setTargetAtTime(0, now, 0.4);   // smooth fade out
    setTimeout(() => { if (!this.playing && this.ctx) this.ctx.suspend(); }, 2500);
    this.paint();
  },

  toggle() {
    const on = !this.playing;
    this.remember(on);
    if (on) this.start(); else this.stop();
    if (window.showToast) showToast(on ? '🎵 Relaxing music on' : 'Music off');
  },

  // follows the site-wide mute (🔊 button / M key)
  applyVolume() {
    if (!this.ctx) return;
    const muted = window.SoundFX && SoundFX.isMuted();
    const target = this.playing && !muted ? this.VOLUME : 0;
    this.master.gain.setTargetAtTime(target, this.ctx.currentTime, 0.8);   // slow fade in
  },

  paint() {
    document.querySelectorAll('[data-music-toggle]').forEach(btn => {
      btn.classList.toggle('active', this.playing);
      btn.setAttribute('aria-pressed', String(this.playing));
      btn.setAttribute('aria-label', this.playing ? 'Background music is on — turn off' : 'Turn on relaxing background music');
      btn.title = this.playing ? 'Music on' : 'Relaxing music';
    });
  }
};

window.Music = Music;

document.addEventListener('DOMContentLoaded', () => {
  // the 🎵 button is created here, next to the 🔊 button (no extra HTML needed)
  document.querySelectorAll('[data-sound-toggle]').forEach(soundBtn => {
    const btn = document.createElement('button');
    btn.type = 'button';
    btn.className = 'btn btn-outline-secondary icon-btn music-btn';
    btn.setAttribute('data-music-toggle', '');
    btn.textContent = '🎵';
    btn.addEventListener('click', () => Music.toggle());
    soundBtn.after(btn);
  });
  Music.paint();

  // music was on before → continue after the first click or key press (browser rule)
  if (Music.wanted()) {
    const resume = e => {
      if (e.target.closest && e.target.closest('[data-music-toggle]')) return;   // the button handles itself
      Music.start();
    };
    document.addEventListener('pointerdown', resume, { once: true });
    document.addEventListener('keydown', resume, { once: true });
  }

  // 🔊 button or M key changed the mute state → follow it
  document.addEventListener('click', e => {
    if (e.target.closest('[data-sound-toggle]')) setTimeout(() => Music.applyVolume(), 0);
  });
  document.addEventListener('keydown', e => {
    if (e.key === 'm' || e.key === 'M') setTimeout(() => Music.applyVolume(), 0);
  });

  // pause in a hidden tab, continue when the user comes back
  document.addEventListener('visibilitychange', () => {
    if (!Music.ctx || !Music.playing) return;
    if (document.hidden) Music.ctx.suspend(); else Music.ctx.resume();
  });
});
